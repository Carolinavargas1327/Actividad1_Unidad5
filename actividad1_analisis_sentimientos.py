from transformers import pipeline
import streamlit as st
import pandas as pd
import plotly.express as px

analizador = pipeline(
    "sentiment-analysis",
    model="pysentimiento/robertuito-sentiment-analysis"
)

texto = st.text_area(
    "Escribe un comentario:",
    placeholder="Ejemplo: Me encanta esta aplicación."
)

if st.button("Analizar sentimiento"):
    if texto.strip():
        resultado = analizador(texto)[0]
        etiqueta = resultado["label"]
        confianza = resultado["score"]

texto = "Me encanta esta aplicación"

resultado = analizador(texto)[0]

etiqueta = resultado["label"]
confianza = resultado["score"]

print("Sentimiento:", etiqueta)
print("Confianza:", f"{confianza:.2%}")

st.metric("Sentimiento identificado", etiqueta)
st.metric("Nivel de confianza", f"{confianza:.2%}")

